#!/bin/bash
# Generated cars (raw/<name>_body_tv.glb, wheels baked in) -> assets/vehicles/<name>_body.glb without wheels + tools/vehicle_json/<name>.json (where the wheels were),
# then scripts/vehicle_data.gd is rewritten from all the JSON files. Delete an output to redo it.
#   name  yaw  tyre-radius-guess(fraction of length)  tris
cd "$(dirname "$0")/.."
BL=${BLENDER:-/opt/blender-4.2.3/blender}
mkdir -p assets/vehicles tools/vehicle_json
prep() {   # name yaw r tris [--front y --rear y --r r]
  [ -f "raw/$1_body_tv.glb" ] || { echo "skip $1"; return; }
  [ -f "assets/vehicles/$1_body.glb" ] && return
  $BL -b -P tools/prep_vehicle.py -- "raw/$1_body_tv.glb" "assets/vehicles/$1_body.glb" "tools/vehicle_json/$1.json" "$2" "$3" "$4" 1024 $5 2>&1 | grep -E "WHEELS|PREP|Error|Trace|no "
}
prep car 180 0.09 6000 "--front 0.265 --rear -0.30 --r 0.085"
prep truck 0 0.08 7000
prep monster 180 0.19 7000 "--front 0.30 --rear -0.36 --r 0.19"
prep sports 180 0.08 6000
prep pickup 180 0.085 6500
prep jeep 180 0.09 6500
prep van 180 0.085 6500
prep taxi 180 0.085 6000
prep police 180 0.085 6500
prep bus 180 0.06 8000
prep firetruck 180 0.065 8000
prep buggy 180 0.11 6000
prep ambulance 180 0.085 6500
python3 - <<'PY'
import glob, json, os
out = ['class_name VehicleData', 'extends RefCounted', '## Generated by tools/prep_vehicles.sh: where the four wheels of each car body are (x, y, z in units of the body length, y is along the car, front = -z in the game),', '## the tyre radius, the width and the height of the body. Do not edit.', '', 'const SPECS := {']
for f in sorted(glob.glob('tools/vehicle_json/*.json')):
    d = json.load(open(f))
    name = os.path.basename(f)[:-5]
    # Blender (x, y, z) -> game (x, z, -y)
    wh = [[round(w[0], 4), round(w[2], 4), round(-w[1], 4)] for w in d['wheels']]
    out.append('\t"%s": {"w": %.4f, "h": %.4f, "r": %.4f, "wheels": %s},' % (name, d['w'], d['h'], d['r'], json.dumps(wh)))
out.append('}')
open('scripts/vehicle_data.gd', 'w').write('\n'.join(out) + '\n')
print('vehicle_data.gd', len(glob.glob('tools/vehicle_json/*.json')), 'cars')
PY
