#!/usr/bin/env node
/**
 * Copies the Three.js skills (https://github.com/cloudai-x/threejs-skills, MIT) into src/lib/skills/threejs/data.ts.
 *   git clone --depth 1 https://github.com/cloudai-x/threejs-skills.git /tmp/threejs-skills
 *   node scripts/vendor-threejs-skills.mjs /tmp/threejs-skills
 * They are plain API notes and examples; the app puts the relevant ones in front of the model whenever it builds a website.
 */
import { execFileSync } from 'node:child_process';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const src = process.argv[2];
if (!src) { console.error('usage: node scripts/vendor-threejs-skills.mjs <path to a clone of threejs-skills>'); process.exit(1); }

const commit = execFileSync('git', ['-C', src, 'rev-parse', 'HEAD']).toString().trim();
const dirs = readdirSync(path.join(src, 'skills')).filter((d) => d.startsWith('threejs-')).sort();
const skills = dirs.map((id) => {
  const raw = readFileSync(path.join(src, 'skills', id, 'SKILL.md'), 'utf8');
  const m = /^---\n([\s\S]*?)\n---\n([\s\S]*)$/.exec(raw);
  if (!m) throw new Error(`${id}: no front matter`);
  const description = /^description:\s*(.+)$/m.exec(m[1])?.[1].trim() ?? '';
  return { id, description, body: m[2].trim() };
});

const out = `// Generated by scripts/vendor-threejs-skills.mjs — do not edit by hand.
// Source: https://github.com/cloudai-x/threejs-skills @ ${commit} (MIT License)

export const THREEJS_SKILLS_SOURCE = { repo: 'https://github.com/cloudai-x/threejs-skills', commit: ${JSON.stringify(commit)}, license: 'MIT' } as const;

export interface ThreejsSkill { id: string; description: string; body: string }

export const THREEJS_SKILLS: ThreejsSkill[] = ${JSON.stringify(skills, null, 2)};
`;
writeFileSync('src/lib/skills/threejs/data.ts', out);
console.log(`wrote ${skills.length} skills, ${(out.length / 1024).toFixed(0)} KB, commit ${commit.slice(0, 7)}`);
