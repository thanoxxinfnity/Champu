#!/usr/bin/env node
/**
 * node scripts/sync-free-catalog.mjs [path/to/data.json]
 *
 * Refreshes src/lib/providers/free-catalog.data.ts from the machine-readable list behind
 * github.com/mnfst/awesome-free-llm-apis (CC0 1.0: free to copy). With no argument it downloads data.json from the
 * pinned commit below; pass a local checkout's data.json to take a newer list, and update COMMIT with it.
 *
 * Only the facts the app needs are kept: provider, key page, base URL, models with context and rate limits, and the
 * footnote text that applies to the provider. How each provider is *called* (dialect, anonymous access, account id) is
 * hand-written in free-catalog.ts, because the list does not carry it.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const COMMIT = '639807877a43bb85b34348ccf7146d7376fc75eb';
const RAW = `https://raw.githubusercontent.com/mnfst/awesome-free-llm-apis/${COMMIT}/data.json`;
const OUT = fileURLToPath(new URL('../src/lib/providers/free-catalog.data.ts', import.meta.url));

const arg = process.argv[2];
const text = arg ? await readFile(arg, 'utf8') : await (await fetch(RAW)).text();
const src = JSON.parse(text);

const plain = (s) => String(s ?? '').replace(/\[([^\]]*)\]\([^)]*\)/g, '$1').replace(/\s+/g, ' ').trim();
const slug = (s) => String(s).toLowerCase().replace(/\(.*?\)/g, '').replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');
const notes = new Map((src.footnotes ?? []).map((f) => [f.id, plain(f.text)]));

const providers = src.providers.map((p) => ({
  id: slug(p.name),
  name: p.name,
  category: p.category,
  flag: p.flag ?? '',
  signupUrl: p.url,
  baseUrl: p.baseUrl,
  description: plain(p.description),
  note: p.footnoteRef != null ? (notes.get(p.footnoteRef) ?? '') : '',
  models: p.models.filter((m) => typeof m.id === 'string' && m.id).map((m) => ({
    id: m.id,
    context: m.context ?? '',
    maxOutput: m.maxOutput ?? '',
    modality: m.modality ?? 'Text',
    rateLimit: m.rateLimit ?? '',
  })),
}));

const out = {
  source: { repo: 'https://github.com/mnfst/awesome-free-llm-apis', commit: COMMIT, lastUpdated: src.lastUpdated, licence: 'CC0-1.0' },
  providers,
};
await writeFile(OUT, `// Generated by scripts/sync-free-catalog.mjs from github.com/mnfst/awesome-free-llm-apis (CC0 1.0). Do not edit by hand.\nexport const FREE_CATALOG_DATA = ${JSON.stringify(out, null, 2)};\n`);
console.log(`${providers.length} providers, ${providers.reduce((n, p) => n + p.models.length, 0)} models → ${OUT}`);
