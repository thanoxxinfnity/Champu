#!/usr/bin/env node
/**
 * Packs src/lib/suites/godot/kit/*.gd into src/lib/suites/godot/kit/data.ts (the files the app writes into every Godot project).
 * Edit the .gd files, run `node scripts/build-game-kit.mjs`; a test fails when data.ts is stale.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const dir = 'src/lib/suites/godot/kit';
const files = readdirSync(dir).filter((f) => f.endsWith('.gd')).sort().map((f) => ({ path: `kit/${f}`, content: readFileSync(path.join(dir, f), 'utf8') }));
const reference = { main_gd: readFileSync(path.join(dir, 'reference/main.gd'), 'utf8'), main_tscn: readFileSync(path.join(dir, 'reference/main.tscn'), 'utf8') };
const out = `// Generated by scripts/build-game-kit.mjs from the .gd files in this folder — do not edit by hand.

export const GAME_KIT_FILES: Array<{ path: string; content: string }> = ${JSON.stringify(files, null, 2)};

/** A complete small game written on the kit: shown to the model as the way to use it, and run in the tests. */
export const GAME_KIT_REFERENCE = ${JSON.stringify(reference, null, 2)};
`;
writeFileSync(path.join(dir, 'data.ts'), out);
console.log(`packed ${files.length} kit scripts, ${(out.length / 1024).toFixed(0)} KB`);
