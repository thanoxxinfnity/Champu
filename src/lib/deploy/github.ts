function utf8ToBase64(text: string): string {
  const bytes = new TextEncoder().encode(text);
  let bin = '';
  for (let i = 0; i < bytes.length; i += 0x8000) bin += String.fromCharCode(...bytes.subarray(i, i + 0x8000));
  return btoa(bin);
}

export interface Who {
  login: string;
  /** The scopes a classic token carries; null for a fine-grained token, which does not report them. */
  scopes: string[] | null;
}

export class GitHubClient {
  private readonly token: string;
  private readonly fetchImpl: FetchLike;
  private readonly sleep: Sleep;
  private readonly api: string;

  constructor(token: string, fetchImpl?: FetchLike, sleep?: Sleep, api = 'https://api.github.com') {
    this.token = token;
    this.fetchImpl = fetchImpl ?? ((u, i) => fetch(u, i));
    this.sleep = sleep ?? ((ms) => new Promise((r) => setTimeout(r, ms)));
    this.api = api;
  }

  private headers(): Record<string, string> {
    return {
      Authorization: `Bearer ${this.token.trim()}`,
      Accept: 'application/vnd.github+json',
      'X-GitHub-Api-Version': '2022-11-28',
      'Content-Type': 'application/json',
    };
  }

  async raw(method: string, path: string, body?: unknown, ok: number[] = [200, 201, 202, 204]): Promise<{ data: any; res: Response }> {
    let res: Response;
    try {
      res = await this.fetchImpl(path.startsWith('http') ? path : `${this.api}${path}`, {
        method,
        headers: this.headers(),
        body: body === undefined ? undefined : JSON.stringify(body),
      });
    } catch (err) {
      throw new GitHubError(`Could not reach GitHub (${(err as Error).message}). Check the connection.`);
    }
    const text = await res.text();
    let data: any = null;
    try {
      data = text ? JSON.parse(text) : null;
    } catch {
      data = text;
    }
    if (!ok.includes(res.status)) {
      let msg: string = (data && typeof data === 'object' && data.message) || (typeof data === 'string' ? data.slice(0, 200) : '') || `HTTP ${res.status}`;
      if (res.status === 401) msg = 'The GitHub token is invalid or expired. Create a new one at github.com/settings/tokens.';
      else if (res.status === 403 && /rate limit/i.test(msg)) msg = 'GitHub is rate limiting this token. Wait a few minutes and try again.';
      else if (res.status === 403 || res.status === 404) msg = `${msg} (the token needs the "repo" and "workflow" scopes, or for a fine-grained token Contents, Workflows and Actions access)`;
      throw new GitHubError(`GitHub ${res.status}: ${msg}`, res.status);
    }
    return { data, res };
  }

  private async req(method: string, path: string, body?: unknown, ok?: number[]) {
    return (await this.raw(method, path, body, ok)).data;
  }

  async whoAmI(): Promise<Who> {
    const { data, res } = await this.raw('GET', '/user');
    const header = res.headers.get('x-oauth-scopes');
    return { login: String(data.login), scopes: header === null ? null : header.split(',').map((s) => s.trim()).filter(Boolean) };
  }

  /** Reuses the repository when it already exists, so a second build of the same app updates the same repo. */
  async ensureRepo(owner: string, name: string, isPublic: boolean): Promise<{ htmlUrl: string; branch: string }> {
    try {
      const r = await this.req('GET', `/repos/${owner}/${name}`);
      return { htmlUrl: r.html_url, branch: r.default_branch ?? 'main' };
    } catch (err) {
      if (!(err instanceof GitHubError) || err.status !== 404) throw err;
    }
    const r = await this.req('POST', '/user/repos', { name, private: !isPublic, auto_init: true, description: 'Built with Chomugiri' });
    await this.sleep(2000);
    return { htmlUrl: r.html_url, branch: r.default_branch ?? 'main' };
  }

  /** One commit with every file, through the Git Data API (so a project of any size is a single push). */
  async pushFiles(owner: string, repo: string, branch: string, files: ProjectFile[], message: string): Promise<string> {
    let ref: any = null;
    for (let i = 0; i < 6; i++) {
      try {
        ref = await this.req('GET', `/repos/${owner}/${repo}/git/ref/heads/${branch}`);
        break;
      } catch (err) {
        // A repository created a moment ago may not have its first commit yet.
        if (!(err instanceof GitHubError) || err.status !== 404 || i === 5) throw err;
        await this.sleep(1500);
      }
    }
    const parent = ref.object.sha as string;
    const parentCommit = await this.req('GET', `/repos/${owner}/${repo}/git/commits/${parent}`);
    const tree: Array<Record<string, string>> = [];
    for (const f of files) {
      if (f.encoding === 'base64') {
        const blob = await this.req('POST', `/repos/${owner}/${repo}/git/blobs`, { content: f.content, encoding: 'base64' });
        tree.push({ path: f.path, mode: '100644', type: 'blob', sha: blob.sha });
      } else {
        // Text goes inline in the tree: no blob request per file.
        tree.push({ path: f.path, mode: '100644', type: 'blob', content: f.content });
      }
    }
    const newTree = await this.req('POST', `/repos/${owner}/${repo}/git/trees`, { base_tree: parentCommit.tree.sha, tree });
    const commit = await this.req('POST', `/repos/${owner}/${repo}/git/commits`, { message, tree: newTree.sha, parents: [parent] });
    await this.req('PATCH', `/repos/${owner}/${repo}/git/refs/heads/${branch}`, { sha: commit.sha });
    return commit.sha as string;
  }

  async findRun(owner: string, repo: string, sha: string, waitMs = 150_000): Promise<any> {
    const until = Date.now() + waitMs;
    for (;;) {
      const r = await this.req('GET', `/repos/${owner}/${repo}/actions/runs?head_sha=${sha}`);
      const runs = (r?.workflow_runs ?? []) as any[];
      if (runs.length) return runs[0];
      if (Date.now() >= until) throw new GitHubError('GitHub Actions did not start a build. Is Actions enabled for the repository (Settings, Actions)?');
      await this.sleep(4000);
    }
  }

  async getRun(owner: string, repo: string, id: number): Promise<any> {
    return this.req('GET', `/repos/${owner}/${repo}/actions/runs/${id}`);
  }

  /** The APK a finished run published: the release of this run first, the latest release as a fallback. */
  async apkUrl(owner: string, repo: string, runNumber: number): Promise<{ apk: string | null; release: string | null }> {
    for (let i = 0; i < 6; i++) {
      for (const path of [`/repos/${owner}/${repo}/releases/tags/build-${runNumber}`, `/repos/${owner}/${repo}/releases/latest`]) {
        try {
          const r = await this.req('GET', path);
          const apk = ((r.assets ?? []) as any[]).find((a) => String(a.name).endsWith('.apk'));
          if (apk) return { apk: apk.browser_download_url as string, release: (r.html_url as string) ?? null };
        } catch {
          // not published yet
        }
      }
      await this.sleep(3000);
    }
    return { apk: null, release: null };
  }

  /** The part of the log that explains a failure. Best effort: a browser may not be allowed to follow the log's redirect. */
  async failureLog(owner: string, repo: string, runId: number, tail = 5000): Promise<string> {
    try {
      const jobs = await this.req('GET', `/repos/${owner}/${repo}/actions/runs/${runId}/jobs`);
      const failed = ((jobs?.jobs ?? []) as any[]).find((j) => j.conclusion === 'failure');
      if (!failed) return 'The build failed but no failed job was found.';
      const step = ((failed.steps ?? []) as any[]).find((s) => s.conclusion === 'failure');
      const res = await this.fetchImpl(`${this.api}/repos/${owner}/${repo}/actions/jobs/${failed.id}/logs`, { headers: this.headers() });
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      const text = (await res.text()).replace(/\x1B\[[0-9;]*m/g, '').replace(/\d{4}-\d\d-\d\dT[\d:.]+Z /g, '');
      const errors = text.split('\n').filter((l) => /error|failed|could not|exception/i.test(l)).slice(-40).join('\n');
      const out = `${step ? `Failed step: ${step.name}\n` : ''}${errors}\n--- end of log ---\n${text.slice(-tail)}`;
      return out.slice(-(tail + 2500));
    } catch {
      return 'The build failed. GitHub did not let the app read the log: open the run page to see it.';
    }
  }
}

