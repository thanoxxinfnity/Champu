export interface BuildPlan {
  /** Everything that is pushed: the project, the workflow and a .gitignore. */
  files: ProjectFile[];
  /** What was left out, and why it is never pushed (workflows are written here, paths cannot climb out). */
  dropped: string[];
  repoName: string;
  label: string;
}

/** What a build pushes, decided without touching the network. Also what the CI check writes to disk and builds. */
export function planBuild(input: ProjectFile[], title: string, kind: BuildKind, repoNameOverride?: string): BuildPlan {
  const label = appLabel(title);
  const repoName = repoNameFor(repoNameOverride ?? title);
  const apkName = repoName.replace(/[^A-Za-z0-9_-]/g, '');
  const { files, dropped } = pushable(input, kind);
  const pubspec = files.find((f) => f.path === 'pubspec.yaml')?.content;
  const workflow =
    kind === 'flutter'
      ? flutterWorkflow({ pkg: dartPackageName(pubspec, repoName), label, apkName })
      : gradleWorkflow({ label, apkName });
  const all: ProjectFile[] = [...files, { path: WORKFLOW_PATH, content: workflow }];
  if (!files.some((f) => f.path === '.gitignore')) all.push({ path: '.gitignore', content: 'build/\n.dart_tool/\n.gradle/\nlocal.properties\n*.keystore\n' });
  return { files: all, dropped, repoName, label };
}

export interface BuildOptions {
  token: string;
  files: ProjectFile[];
  title: string;
  /** Overrides the detected kind. */
  kind?: BuildKind;
  repoName?: string;
  /** A public repository gives a download link that opens without signing in to GitHub. Default true. */
  isPublic?: boolean;
  onStep?: (text: string) => void;
  fetchImpl?: FetchLike;
  sleep?: Sleep;
  /** Give up waiting for the build after this long. Default 45 minutes. */
  timeoutMs?: number;
  pollMs?: number;
  /** For a repeat build, the commit message names it. */
  now?: () => number;
}

export interface BuildOutcome {
  ok: boolean;
  owner: string;
  repo: string;
  repoUrl: string;
  runUrl: string | null;
  runNumber: number | null;
  apkUrl: string | null;
  releaseUrl: string | null;
  /** On failure: the part of the log that explains it. */
  log?: string;
  dropped: string[];
  kind: BuildKind;
}

export async function buildOnGitHub(opts: BuildOptions): Promise<BuildOutcome> {
  const step = opts.onStep ?? (() => undefined);
  const sleep = opts.sleep ?? ((ms: number) => new Promise<void>((r) => setTimeout(r, ms)));
  const now = opts.now ?? Date.now;

  if (!opts.token.trim()) throw new GitHubError('Add your GitHub token first: Settings, Keys, GitHub token.');
  const kind = opts.kind ?? detectProject(opts.files.map((f) => f.path));
  if (!canBuildApk(kind)) {
    throw new GitHubError(
      kind === 'web'
        ? 'This is a website, not an app: it has no APK. Use Deploy (Vercel) to put it online.'
        : 'Nothing to build: a Flutter project needs pubspec.yaml and a Gradle Android project needs settings.gradle.kts.',
    );
  }

  const gh = new GitHubClient(opts.token, opts.fetchImpl, sleep);
  const plan = planBuild(opts.files, opts.title, kind, opts.repoName);
  const { repoName, dropped } = plan;

  step('Checking the GitHub token');
  const who = await gh.whoAmI();
  if (who.scopes && !(who.scopes.includes('repo') || who.scopes.includes('public_repo')) ) {
    throw new GitHubError(`The token is valid but has no "repo" scope (it has: ${who.scopes.join(', ') || 'none'}). Create a classic token with repo and workflow.`);
  }
  if (who.scopes && !who.scopes.includes('workflow')) {
    throw new GitHubError('The token has no "workflow" scope, so it cannot add the build workflow. Create a classic token with repo and workflow.');
  }

  step(`Preparing repository ${who.login}/${repoName}`);
  const repo = await gh.ensureRepo(who.login, repoName, opts.isPublic ?? true);

  const all = plan.files;

  step(`Pushing ${all.length} files`);
  const sha = await gh.pushFiles(who.login, repoName, repo.branch, all, `Chomugiri: build ${new Date(now()).toISOString().slice(0, 16).replace('T', ' ')}`);

  step('Waiting for GitHub Actions to start');
  const first = await gh.findRun(who.login, repoName, sha);
  const runUrl = (first.html_url as string) ?? null;
  step('Building the APK (about 4 to 8 minutes)');

  const started = now();
  const pollMs = opts.pollMs ?? 8000;
  const limit = opts.timeoutMs ?? 45 * 60_000;
  let run = first;
  let lastNote = started;
  while (run.status !== 'completed') {
    await sleep(pollMs);
    run = await gh.getRun(who.login, repoName, run.id as number);
    const t = now();
    if (t - lastNote >= 30_000) {
      step(`Still building: ${Math.floor((t - started) / 60_000)} min, ${String(run.status).replace('_', ' ')}`);
      lastNote = t;
    }
    if (t - started > limit) throw new GitHubError(`The build did not finish in ${Math.round(limit / 60_000)} minutes. Open the run on GitHub to see where it is: ${runUrl}`);
  }

  const base = { owner: who.login, repo: repoName, repoUrl: repo.htmlUrl, runUrl, runNumber: (run.run_number as number) ?? null, dropped, kind };
  if (run.conclusion === 'success') {
    const found = await gh.apkUrl(who.login, repoName, run.run_number as number);
    step(found.apk ? 'APK ready' : 'Build passed, but no APK was found on the release');
    return { ok: Boolean(found.apk), ...base, apkUrl: found.apk, releaseUrl: found.release, ...(found.apk ? {} : { log: 'The build passed but the release has no .apk file. Open the run page.' }) };
  }
  step('The build failed');
  const log = await gh.failureLog(who.login, repoName, run.id as number);
  return { ok: false, ...base, apkUrl: null, releaseUrl: null, log };
}

/** For the Settings "Check token" button. */
export async function checkGitHubToken(token: string, fetchImpl?: FetchLike): Promise<{ ok: boolean; message: string }> {
  if (!token.trim()) return { ok: false, message: 'Paste a token first.' };
  try {
    const who = await new GitHubClient(token, fetchImpl).whoAmI();
    if (who.scopes === null) return { ok: true, message: `Signed in as ${who.login}. This is a fine-grained token: it needs Contents, Workflows and Actions (read and write) on the repositories it builds.` };
    const missing = ['repo', 'workflow'].filter((s) => !who.scopes!.includes(s));
    if (missing.length) return { ok: false, message: `Signed in as ${who.login}, but the token lacks: ${missing.join(', ')}. Create a classic token with repo and workflow.` };
    return { ok: true, message: `Signed in as ${who.login}. The token can build APKs (repo and workflow).` };
  } catch (err) {
    return { ok: false, message: (err as Error).message };
  }
}
