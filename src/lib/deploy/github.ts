/**
 * Build an APK on GitHub Actions, from the phone, with the user's own GitHub token.
 *
 * The flow is the one a person would do by hand: push the generated project to a repository of their own, let a
 * workflow build it, wait, hand back the download link. No computer and no Android toolchain needed.
 *
 * Everything here takes `fetch` and `sleep` as arguments, so it runs the same in the browser, in the Android shell's
 * WebView (api.github.com allows browser requests, so no proxy is needed) and in a test against a fake GitHub.
 *
 * Projects without an APK (a website) do not come through here: they go to Vercel with the Vercel token, see
 * `deploy/state.ts` and the Deploy button.
 */

export type FetchLike = (input: string, init?: RequestInit) => Promise<Response>;
export type Sleep = (ms: number) => Promise<void>;

export class GitHubError extends Error {
  // Written out (no parameter properties) so the code also runs under node's strip-only TypeScript, which the tests use.
  readonly status?: number;
  constructor(message: string, status?: number) {
    super(message);
    this.name = 'GitHubError';
    this.status = status;
  }
}

export type BuildKind = 'flutter' | 'gradle';
export type ProjectKind = BuildKind | 'web' | 'unknown';

export interface ProjectFile {
  path: string;
  content: string;
  /** `base64` for binary files; anything else is UTF-8 text. */
  encoding?: 'utf-8' | 'base64';
}

// ── What kind of project is this? ───────────────────────────────────────────

/** Which build a set of files needs. Only `flutter` and `gradle` make an APK on GitHub; `web` ships to Vercel. */
export function detectProject(paths: string[]): ProjectKind {
  const has = (p: string) => paths.includes(p);
  if (has('pubspec.yaml')) return 'flutter';
  if (has('settings.gradle.kts') || has('settings.gradle')) return 'gradle';
  if (paths.some((p) => /^(index\.html|public\/index\.html|package\.json|app\/page\.(t|j)sx?|src\/app\/page\.(t|j)sx?|pages\/index\.(t|j)sx?)$/.test(p))) return 'web';
  return 'unknown';
}

export function canBuildApk(kind: ProjectKind): kind is BuildKind {
  return kind === 'flutter' || kind === 'gradle';
}

/** A repository name GitHub accepts. */
export function repoNameFor(title: string): string {
  const slug = title
    .toLowerCase()
    .replace(/[^a-z0-9._-]+/g, '-')
    .replace(/^[-._]+|[-._]+$/g, '')
    .replace(/-{2,}/g, '-')
    .slice(0, 60);
  return slug || 'chomugiri-app';
}

/** The name under the launcher icon. Only characters that cannot break a shell line or a YAML string. */
export function appLabel(title: string): string {
  const label = title.replace(/[^A-Za-z0-9 _-]/g, '').trim().slice(0, 40);
  return label || 'Chomugiri App';
}

/** Dart package name from pubspec.yaml, which `flutter create --project-name` must be given. */
export function dartPackageName(pubspec: string | undefined, fallback: string): string {
  const m = pubspec ? /^name:\s*["']?([A-Za-z0-9_]+)["']?\s*(#.*)?$/m.exec(pubspec) : null;
  let name = (m?.[1] ?? fallback).toLowerCase().replace(/[^a-z0-9_]+/g, '_').replace(/^_+|_+$/g, '');
  if (!name || /^[0-9]/.test(name)) name = `app_${name}`;
  return name;
}

/** Files that must never be pushed from a model's output: workflows are written here, and paths cannot climb out. */
export function pushable(files: ProjectFile[], kind: BuildKind): { files: ProjectFile[]; dropped: string[] } {
  const dropped: string[] = [];
  const out: ProjectFile[] = [];
  for (const f of files) {
    const p = f.path.replace(/^\.\//, '');
    const unsafe = p.startsWith('/') || p.split('/').includes('..') || p.includes('\\');
    // Flutter's android/ folder is generated by `flutter create` in the workflow, so a copy written by a model is only a risk.
    const generated = kind === 'flutter' && (p.startsWith('android/') || p.startsWith('ios/'));
    if (unsafe || generated || p.startsWith('.github/')) {
      dropped.push(f.path);
      continue;
    }
    out.push({ ...f, path: p });
  }
  return { files: out, dropped };
}

