const SIGN_STEP = (indent: string) =>
  [
    '- name: Use the fixed sideload key (so a new build installs over the old one)',
    '  run: |',
    '    mkdir -p ~/.android',
    `    echo "${SIDELOAD_KEYSTORE_BASE64}" | base64 -d > ~/.android/debug.keystore`,
  ]
    .map((l) => indent + l)
    .join('\n');

const PUBLISH_STEP = (indent: string, apkGlob: string, name: string, label: string) =>
  [
    '- name: Publish the APK as a release (download link)',
    '  env:',
    '    GH_TOKEN: ${{ github.token }}',
    '  run: |',
    `    apk="$(ls ${apkGlob} | head -n 1)"`,
    `    cp "$apk" "${name}.apk"`,
    `    gh release create "build-\${{ github.run_number }}" "${name}.apk" --target "\${{ github.sha }}" --title "${label} build \${{ github.run_number }}" --notes "Built by Chomugiri. Debug-grade build signed with the public sideload key: it installs over the previous build of this app." --latest`,
  ]
    .map((l) => indent + l)
    .join('\n');

/** The workflow for a Flutter project: the android/ scaffold is generated, then the release APK is built. */
export function flutterWorkflow(opts: { pkg: string; label: string; apkName: string }): string {
  return `name: Build APK
on:
  push:
  workflow_dispatch:
permissions:
  contents: write
concurrency:
  group: build-\${{ github.ref }}
  cancel-in-progress: true
jobs:
  build:
    runs-on: ubuntu-latest
    timeout-minutes: 40
    steps:
      - uses: actions/checkout@v4
      - uses: actions/setup-java@v4
        with:
          distribution: temurin
          java-version: '17'
      - uses: subosito/flutter-action@v2
        with:
          channel: stable
          cache: true
      - name: Generate the Android scaffold
        run: |
          flutter create --platforms=android --project-name ${opts.pkg} --org com.chomugiri --description "${opts.label}" /tmp/scaffold
          rm -rf android
          cp -r /tmp/scaffold/android ./android
          sed -i 's|<application|<uses-permission android:name="android.permission.INTERNET"/>\\n    <application|' android/app/src/main/AndroidManifest.xml
          sed -i 's|android:label="[^"]*"|android:label="${opts.label}"|' android/app/src/main/AndroidManifest.xml
${SIGN_STEP('      ')}
      - run: flutter pub get
      - run: flutter build apk --release --build-number=\${{ github.run_number }}
      - uses: actions/upload-artifact@v4
        with:
          name: apk
          path: build/app/outputs/flutter-apk/app-release.apk
${PUBLISH_STEP('      ', 'build/app/outputs/flutter-apk/app-release.apk', opts.apkName, opts.label)}
`;
}

